/**
 * Writes `src/lib/cloud/api.gen.ts`, the types of the sitegloss.dev API
 * (version 1), from the copy of its OpenAPI document kept in this
 * repository (`src/lib/cloud/openapi-v1.json`). Both files are committed: a
 * build and CI need neither the server's repository nor the network.
 *
 *   bun scripts/api-types.ts                 the types, from the copy here
 *   bun scripts/api-types.ts --check         fail when the types are not what
 *                                            the copy gives (the tests run it)
 *
 * A new copy of the server's packages/api/openapi/v1.json comes with
 * `bun scripts/sync-vectors.ts`, byte for byte (Biome leaves it as it is),
 * which writes the types too.
 *
 * openapi-typescript is a dev dependency only: nothing of it is in the
 * extension, which has the types and no code from them.
 */

import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";

const ROOT = join(import.meta.dir, "..");
export const SPEC = join(ROOT, "src/lib/cloud/openapi-v1.json");
export const TYPES = join(ROOT, "src/lib/cloud/api.gen.ts");

const HEADER = `/**
 * The sitegloss.dev API, version 1, as types. Generated by
 * \`bun scripts/api-types.ts\` from \`openapi-v1.json\`: do not edit.
 */

`;

/** Biome's formatting of `text`, as the file `name` would get it. */
async function formatted(name: string, text: string): Promise<string> {
	const run = Bun.spawn(
		[
			join(ROOT, "node_modules/.bin/biome"),
			"format",
			`--stdin-file-path=${name}`,
		],
		{ cwd: ROOT, stdin: new Blob([text]), stdout: "pipe", stderr: "pipe" },
	);
	const [out, problem, code] = await Promise.all([
		new Response(run.stdout).text(),
		new Response(run.stderr).text(),
		run.exited,
	]);
	if (code !== 0) throw new Error(`biome could not format ${name}: ${problem}`);
	return out;
}

/** The types the document at `spec` gives, formatted as this repository's code. */
export async function typesOf(spec: string): Promise<string> {
	const out = await mkdtemp(join(tmpdir(), "sitegloss-api-types-"));
	try {
		const built = await Bun.build({
			entrypoints: [join(import.meta.dir, "api-types-run.ts")],
			outdir: out,
			target: "bun",
			plugins: [
				{
					name: "typescript-5",
					setup(build) {
						build.onResolve({ filter: /^typescript$/ }, () => ({
							path: Bun.resolveSync("typescript-5", ROOT),
						}));
					},
				},
			],
		});
		if (!built.success)
			throw new AggregateError(built.logs, "the generator did not build");
		const { generate } = (await import(join(out, "api-types-run.js"))) as {
			generate: (spec: URL) => Promise<string>;
		};
		return await formatted(
			TYPES,
			HEADER + (await generate(Bun.pathToFileURL(spec))),
		);
	} finally {
		await rm(out, { recursive: true, force: true });
	}
}

if (import.meta.main) {
	const args = process.argv.slice(2);
	const check = args.includes("--check");
	const types = await typesOf(SPEC);
	if (check) {
		if ((await Bun.file(TYPES).text()) !== types) {
			console.error(
				"src/lib/cloud/api.gen.ts is not what openapi-v1.json gives: run bun scripts/api-types.ts",
			);
			process.exit(1);
		}
		console.log("api.gen.ts is up to date");
	} else {
		await Bun.write(TYPES, types);
		console.log("Wrote src/lib/cloud/api.gen.ts");
	}
}
